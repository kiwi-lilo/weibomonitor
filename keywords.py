def build_queries(districts: list[str]) -> list[tuple[str, str]]:
    """返回 (区县, 搜索词) 组合，便于按区县控制兜底策略"""
    queries = [(dist, f"{dist} {kw}") for dist in districts for kw in SEARCH_NEGATIVE_KW]
    if districts:
        city = districts[0]
        queries.extend((city, f"{city} {kw}") for kw in CITY_FOCUS_KW)
    return queries


