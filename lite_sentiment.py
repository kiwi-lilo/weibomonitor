# 否定词：出现在情感词前 ≤2 字符内则翻转极性
NEGATORS = ("不", "没", "没有", "别", "无", "未", "非", "莫", "毫无", "并未", "并不")

# 程度副词：缩放最近的情感词权重
DEGREE = {
    "太": 1.6, "很": 1.4, "非常": 1.6, "特别": 1.5, "十分": 1.5, "极其": 1.8,
    "真的": 1.4, "真是": 1.4, "超": 1.5, "巨": 1.5, "贼": 1.4, "老": 1.3,
    "这么": 1.3, "那么": 1.3, "如此": 1.4, "相当": 1.3,
    "有点": 0.7, "有些": 0.7, "稍微": 0.6, "略": 0.6, "还算": 0.6,
}

# 预编译：按长度降序保证最长匹配优先（"态度恶劣"先于"差"）
_ALL_WORDS = sorted(set(NEG) | set(POS), key=len, reverse=True)
_WORD_RE = re.compile("|".join(map(re.escape, _ALL_WORDS)))
_DEG_RE = re.compile("|".join(map(re.escape, sorted(DEGREE, key=len, reverse=True))))


def _score_one(text: str) -> float:
    """单条文本 → P(负面)"""
    text = text[:300]
    neg_sum = pos_sum = 0.0
    consumed_end = -1
    for m in _WORD_RE.finditer(text):
        if m.start() < consumed_end:      # 避免重叠计分
            continue
        consumed_end = m.end()
        word = m.group()
        weight = float(NEG.get(word) or POS.get(word))
        polarity_neg = word in NEG

        # 前视否定（情感词前 3 字符窗口）
        window = text[max(0, m.start() - 3):m.start()]
        if any(window.endswith(n) for n in NEGATORS):
            polarity_neg = not polarity_neg
            weight *= 0.8                 # "不满意"负面强度略低于"很差"

        # 前视程度副词（前 4 字符窗口）
        dwin = text[max(0, m.start() - 4):m.start()]
        dm = None
        for d in _DEG_RE.finditer(dwin):
            dm = d
        if dm and dwin.endswith(dm.group()):
            weight *= DEGREE[dm.group()]

        if polarity_neg:
            neg_sum += weight
        else:
            pos_sum += weight

    # 感叹号/问号连用增强主导情绪
    bangs = text.count("！") + text.count("!") + text.count("？？") + text.count("??")
    boost = 1 + min(bangs, 5) * 0.12
    if neg_sum >= pos_sum:
        neg_sum *= boost
    else:
        pos_sum *= boost

    raw = neg_sum - pos_sum
    return 1 / (1 + math.exp(-raw / 2.5))     # sigmoid → [0,1]


def score_texts(texts: list[str], **_kw) -> list[float]:
    """接口与 local_model.score_texts 对齐"""
    return [_score_one(t) for t in texts]


